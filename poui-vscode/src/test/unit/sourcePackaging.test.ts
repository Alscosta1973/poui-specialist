describe('collectSourceFiles + stageSources', () => {
  let root: string;
  let stage: string;

  beforeEach(async () => {
    root = await fs.mkdtemp(path.join(os.tmpdir(), 'poui-src-'));
    stage = await fs.mkdtemp(path.join(os.tmpdir(), 'poui-stage-'));
    const files: Record<string, string> = {
      'package.json': JSON.stringify({ dependencies: { '@angular/core': '^21.2.0', '@po-ui/ng-components': '^21.34.1' } }),
      'package-lock.json': '{}',
      'angular.json': '{}',
      'proxy.conf.json': JSON.stringify({ '/rest': { target: 'http://localhost:8080', headers: { Authorization: 'Basic eDp5' } } }),
      'protheus-dev.secret': 'Basic eDp5',
      'src/app/app.ts': 'export class App {}',
      'src/app/app.spec.ts': 'describe("x", () => {});',
      'node_modules/lib/index.js': 'x',
      'dist/meu-app/index.html': '<html></html>',
      'Resource/meu-app.app': 'zip',
      '.vscode/settings.json': '{}',
    };
    for (const [rel, content] of Object.entries(files)) {
      await fs.mkdir(path.dirname(path.join(root, rel)), { recursive: true });
      await fs.writeFile(path.join(root, rel), content, 'utf8');
    }
  });

  afterEach(async () => {
    await fs.rm(root, { recursive: true, force: true });
    await fs.rm(stage, { recursive: true, force: true });
  });

  it('walks the project (no git) and returns only the client source files', async () => {
    const files = (await collectSourceFiles(root, async () => undefined)).sort();
    assert.deepStrictEqual(files, ['angular.json', 'package-lock.json', 'package.json', 'src/app/app.spec.ts', 'src/app/app.ts']);
  });

  it('uses the git listing when available, still filtered', async () => {
    const files = await collectSourceFiles(root, async () => ['src/app/app.ts', 'Resource/meu-app.app', 'proxy.conf.json', 'package.json']);
    assert.deepStrictEqual(files.sort(), ['package.json', 'src/app/app.ts']);
  });

  it('stages <project>/ with the sources, proxy example and LEIA-ME, without the local proxy', async () => {
    const files = await collectSourceFiles(root, async () => undefined);
    const result = await stageSources(root, stage, 'meu-app', files, 'v22.0.0');
    const base = path.join(stage, 'meu-app');
    assert.ok(await exists(path.join(base, 'src/app/app.ts')));
    assert.ok(await exists(path.join(base, 'LEIA-ME.md')));
    assert.ok(!(await exists(path.join(base, 'proxy.conf.json'))));
    assert.ok(!(await exists(path.join(base, 'node_modules'))));
    const example = await fs.readFile(path.join(base, 'proxy.conf.example.json'), 'utf8');
    assert.ok(!example.includes('eDp5'));
    assert.strictEqual(result.fileCount, files.length + 2);
    assert.deepStrictEqual(result.warnings, []);
    const leiaMe = await fs.readFile(path.join(base, 'LEIA-ME.md'), 'utf8');
    assert.ok(leiaMe.includes('^21.34.1'));
  });
});

async function exists(p: string): Promise<boolean> {
  return fs
    .access(p)
    .then(() => true)
    .catch(() => false);
}
